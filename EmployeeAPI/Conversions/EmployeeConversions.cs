      public static IEnumerable<Employee> ConvertToModel(this IEnumerable<EmployeeDTO> employeeDTOs) {
         return (from employeeDTO in employeeDTOs
                 select new Model.Employee {
                    EmployeeId = employeeDTO.EmployeeId,
                    Name = employeeDTO.Name,
                    NIK = employeeDTO.NIK,
                    NoKK = employeeDTO.NoKK,
                    DepartmentId = employeeDTO.DepartmentId,
                    PositionId = employeeDTO.PositionId,
                    Pendidikan = employeeDTO.Pendidikan,
                    Gender = (bool)employeeDTO.Gender,
                    LocBirth = employeeDTO.LocBirth,
                    DateBirth = employeeDTO.DateBirth,
