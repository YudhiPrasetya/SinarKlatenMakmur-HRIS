using EmployeeAPI.Model;
using SKM.Shared.Dtos;

namespace EmployeeAPI.Conversions {
    public static class EmployeeConversions {
      public static IEnumerable<EmployeeDTO> ConvertToDtO(this IEnumerable<Employee> employees) {
         return (from employee in employees
                 select new EmployeeDTO {
                    EmployeeId = employee.EmployeeId,
                    Name = employee.Name,
                    NIK = employee.NIK,
                    NoKK = employee.NoKK,
                    DepartmentId = employee.DepartmentId,
                    PositionId = employee.PositionId,
                    Pendidikan = employee.Pendidikan,
                    Gender = employee.Gender,
                    LocBirth = employee.LocBirth,
                    DateBirth = employee.DateBirth,
                    KTP = employee.KTP,
                    Address = employee.Address,
                    EmployeeDate = employee.EmployeeDate,
                    IsActive = employee.IsActive,
                    IsStaff = employee.IsStaff,
                    BankName = employee.BankName,
                    AccountBank = employee.AccountBank,
                    NOBPJSKS = employee.NOBPJSKS,
                    NOBPJSPEN = employee.NOBPJSPEN,
                    MarriedStatus = employee.MarriedStatus,
                    EmployeeStatus = employee.EmployeeStatus,
                    StartActiveDate = employee.StartActiveDate,
                    ContractEndDate = employee.ContractEndDate,
                    ContractStartDate = employee.ContractStartDate,
                    MotherName = employee.MotherName,
                    PhoneNumber = employee.PhoneNumber,
                    CreatedAt = employee.CreatedAt,
                    CreatedBy = employee.CreatedBy,
                    UpdatedAt = employee.UpdatedAt,
                    UpdatedBy = employee.UpdatedBy,
                    NOBPJSTK= employee.NOBPJSTK,
                    EndEmpDate= employee.EndEmpDate,
                    GroupID=employee.GroupID,
                    GroupName=employee.GroupName,
                    PositionName=employee.PositionName,
                    DepartmentName = employee.DepartmentName
                 }).ToList<EmployeeDTO>();
      }

