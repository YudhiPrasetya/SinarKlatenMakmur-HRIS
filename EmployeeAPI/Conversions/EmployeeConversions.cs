                    IsActive = employeeDTO.IsActive,
                    IsStaff = employeeDTO.IsStaff,
                    BankName = employeeDTO.BankName,
                    AccountBank = employeeDTO.AccountBank,
                    NOBPJSKS = employeeDTO.NOBPJSKS,
                    NOBPJSPEN = employeeDTO.NOBPJSPEN,
                    MarriedStatus = employeeDTO.MarriedStatus,
                    EmployeeStatus = employeeDTO.EmployeeStatus,
                    StartActiveDate = employeeDTO.StartActiveDate,
                    ContractEndDate = employeeDTO.ContractEndDate,
                    ContractStartDate = employeeDTO.ContractStartDate,
                    MotherName = employeeDTO.MotherName,
                    PhoneNumber = employeeDTO.PhoneNumber,
                    CreatedAt = employeeDTO.CreatedAt,
                    CreatedBy = employeeDTO.CreatedBy,
                    UpdatedAt = employeeDTO.UpdatedAt,
                    UpdatedBy = employeeDTO.UpdatedBy,
                    NOBPJSTK = employeeDTO.NOBPJSTK,
                    EndEmpDate = employeeDTO.EndEmpDate,
                    GroupID= employeeDTO.GroupID,
                    GroupName= employeeDTO.GroupName,
                    PositionName= employeeDTO.PositionName,
                    DepartmentName= employeeDTO.DepartmentName
                 }).ToList<Model.Employee>();
      }

